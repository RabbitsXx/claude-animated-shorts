// Asset catalogue (pure part of studio2/catalog-assets.mjs): sounds, music and prop builders from every film, searchable by words.
const STOP=new Set('a an the and or of on in at to for with from by its it is are was no not no voices voice comedic cartoon sound sounds clean short long very over into then than that this one two small big loop loopable'.split(' '));
export function tagsFrom(id,prompt=''){
 const words=`${String(id).replace(/[-_]/g,' ')} ${prompt}`.toLowerCase().match(/[a-z]{3,}/g)||[];
 return [...new Set(words.filter(w=>!STOP.has(w)))].slice(0,14);
}
export function propsFromSource(src){
 const lines=src.split('\n'),out=[];
 lines.forEach((l,i)=>{
  const m=l.match(/^export function (build\w+)\(([^)]*)\)/);if(!m)return;
  const prev=(lines[i-1]||'').trim(),comment=prev.startsWith('//')&&!prev.startsWith('// ----')?prev.replace(/^\/\/\s*/,''):'';
  out.push({name:m[1],sig:m[2],comment});
 });
 return out;
}
export function buildCatalog({sfx=[],music=[],props=[]}){
 const entries=[];
 for(const s of sfx)entries.push({kind:'sfx',id:s.id,path:s.path,seconds:s.seconds??null,prompt:s.prompt||'',tags:tagsFrom(s.id,s.prompt),origin:s.film||'studio'});
 for(const m of music)entries.push({kind:'music',id:m.id,path:m.path,seconds:m.seconds??null,prompt:m.prompt||'',tags:tagsFrom(m.id,m.prompt),origin:m.film||'studio'});
 for(const p of props)entries.push({kind:'prop',id:`${p.film}:${p.name}`,path:p.file,seconds:null,prompt:p.comment||'',sig:p.sig,tags:tagsFrom(p.name.replace(/^build/,'').replace(/([A-Z])/g,' $1'),p.comment),origin:p.film});
 return {about:'Generated by node studio2/catalog-assets.mjs. Search: node studio2/catalog-assets.mjs --find "egg splat" [--kind sfx|music|prop]. Reuse before you generate or rewrite.',entries};
}
export function findEntries(catalog,query,{kind=null,limit=8}={}){
 const q=tagsFrom('',query);if(!q.length)return [];
 return catalog.entries.filter(e=>!kind||e.kind===kind)
  .map(e=>({e,score:q.filter(w=>e.tags.includes(w)||e.tags.some(t=>t.startsWith(w)&&w.length>3)).length}))
  .filter(x=>x.score>0).sort((a,b)=>b.score-a.score).slice(0,limit).map(x=>x.e);
}
